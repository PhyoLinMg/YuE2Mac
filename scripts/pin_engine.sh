#!/bin/zsh
# pin_engine.sh — downloads the engine's Python files at ONE Hugging Face commit,
# shows you where to read them, and (if you approve) writes their commit + SHA-256
# into YuE2Mac/Core/EnginePin.swift. The app refuses to install or run anything else.
#
#   bash scripts/pin_engine.sh               # pin the repo's current commit
#   bash scripts/pin_engine.sh <commit-sha>  # pin a specific commit
set -euo pipefail
cd "$(dirname "$0")/.."

REPO=$(sed -n 's/.*static let modelRepo = "\(.*\)".*/\1/p' YuE2Mac/Core/SetupManager.swift)
FILES=(generate.py yue2_model.py yue2_vae.py)
REV="${1:-}"

if [[ -z "$REV" ]]; then
  REV=$(curl -fsSL "https://huggingface.co/api/models/$REPO" | plutil -extract sha raw -o - -)
fi
[[ "$REV" =~ ^[0-9a-f]{40}$ ]] || { echo "❌ Not a full commit SHA: $REV"; exit 1; }

DIR="engine-review/$REV"
mkdir -p "$DIR"
echo "▸ $REPO @ $REV → $DIR"
for f in $FILES; do
  curl -fsSL "https://huggingface.co/$REPO/resolve/$REV/$f" -o "$DIR/$f"
done

echo "\n▸ SHA-256"
typeset -A HASH
for f in $FILES; do
  HASH[$f]=$(shasum -a 256 "$DIR/$f" | awk '{print $1}')
  printf "  %s  %s (%s lines)\n" "$HASH[$f]" "$f" "$(wc -l < "$DIR/$f" | tr -d ' ')"
done

echo "\n▸ Lines worth a look (network, processes, dynamic code, pickle):"
grep -nE 'import (subprocess|socket|requests|urllib|http|ctypes|pickle|marshal)|from (subprocess|socket|requests|urllib|http)|os\.(system|popen|exec|spawn|remove|unlink)|shutil\.rmtree|\beval\(|\bexec\(|__import__|compile\(|base64|allow_pickle *= *True|torch\.load|Path\.home|expanduser' \
  "$DIR"/*.py || echo "  (none found — still skim the files yourself)"

echo "\nRead the files in $DIR before continuing."
read -q "REPLY?Pin these exact files into the app? [y/N] " || { echo "\nNot pinned."; exit 1; }
echo

cat > YuE2Mac/Core/EnginePin.swift <<SWIFT
//
//  EnginePin.swift — the exact engine code this build is allowed to run.
//  Generated by \`scripts/pin_engine.sh\` after you review the Python files.
//  Empty = unpinned: setup refuses to install and the app won't generate.
//

enum EnginePin {
    /// Hugging Face commit SHA of \`SetupManager.modelRepo\` (covers scripts and weights).
    static let revision = "$REV"

    /// SHA-256 of each file in \`SetupManager.engineScripts\` at \`revision\`.
    static let scriptSHA256: [String: String] = [
        "generate.py": "$HASH[generate.py]",
        "yue2_model.py": "$HASH[yue2_model.py]",
        "yue2_vae.py": "$HASH[yue2_vae.py]",
    ]

    static var isPinned: Bool {
        isHex(revision, count: 40) &&
        SetupManager.engineScripts.allSatisfy { isHex(scriptSHA256[\$0] ?? "", count: 64) }
    }

    private static func isHex(_ s: String, count: Int) -> Bool {
        s.count == count && s.allSatisfy { \$0.isHexDigit && !\$0.isUppercase }
    }
}
SWIFT
echo "✓ Pinned. Rebuild the app (bash scripts/run_app.sh), then press Download & Install."
